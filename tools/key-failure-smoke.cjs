'use strict';
// Verify encrypted key persistence and races using only fake keys, a local fake API and isolated profiles.
const { spawn } = require('node:child_process');
const fs = require('node:fs/promises');
const http = require('node:http');
const os = require('node:os');
const path = require('node:path');
const assert = require('node:assert/strict');
const { connect, freePort } = require('./guide-shots/cdp');

(async () => {
  const root = path.resolve(__dirname, '..'), tmp = await fs.mkdtemp(path.join(os.tmpdir(), 'snowball-keys-ui-'));
  const profile = path.join(tmp, 'profile'), data = path.join(tmp, 'data');
  await fs.mkdir(profile); await fs.mkdir(data);
  await fs.writeFile(path.join(profile, 'settings.json'), JSON.stringify({ dataDir: data }));
  await fs.writeFile(path.join(data, 'profile.json'), JSON.stringify({ name: 'Тест', welcomed: true }));
  const held = new Map(), seen = [];
  const server = http.createServer((req, res) => {
    req.resume();
    req.on('end', () => {
      const auth = String(req.headers.authorization || '');
      seen.push(auth);
      const reply = () => { res.setHeader('content-type', 'application/json'); res.end(JSON.stringify({ id: 'r1', object: 'response', status: 'completed', output: [] })); };
      if (auth.endsWith('slow-delete')) held.set('delete', reply);
      else if (auth.endsWith('slow-old')) held.set('old', reply);
      else reply();
    });
  });
  await new Promise((resolve) => server.listen(0, '127.0.0.1', resolve));
  let child;
  const launch = (dir, inspect, debug) => spawn(require('electron'), ['.', '--inspect=' + inspect, '--remote-debugging-port=' + debug, '--user-data-dir=' + dir],
    { cwd: root, env: { ...process.env, OPENAI_BASE_URL: 'http://127.0.0.1:' + server.address().port + '/v1' }, stdio: 'ignore', windowsHide: true });
  const stop = async () => { if (!child) return; child.kill(); await new Promise((resolve) => child.exitCode !== null ? resolve() : child.once('exit', resolve)); child = null; };
  const waitHeld = async (key) => { for (let i = 0; i < 100 && !held.has(key); i++) await new Promise((r) => setTimeout(r, 30)); assert.ok(held.has(key), 'fake request was not received'); };
  let inspectPort, debugPort;
  try {
    [inspectPort, debugPort] = await Promise.all([freePort(), freePort()]);
    child = launch(profile, inspectPort, debugPort);
    const main = await connect(inspectPort, (t) => t.type === 'node');
    assert.equal(path.resolve(await main.ev("process.mainModule.require('electron').app.getPath('userData')")), path.resolve(profile));
    const page = await connect(debugPort, (t) => /index\.html/.test(t.url));
    await page.until('!!window.vsApi && document.readyState === "complete"');
    assert.equal((await page.ev(`vsApi.assistantCheckKey('openai','sk-test-first')`)).ok, true);
    const keyFile = path.join(profile, 'openai-key.bin'), old = await fs.readFile(keyFile);
    assert.equal(old.includes(Buffer.from('sk-test-first')), false);
    await main.ev(`(() => {const fs=process.mainModule.require('fs').promises;global.snowKeyRename=fs.rename;
      fs.rename=async(from,to)=>{if(to===${JSON.stringify(keyFile)}){const e=new Error('disk full');e.code='ENOSPC';throw e}return global.snowKeyRename(from,to)};return true;})()`);
    const failed = await page.ev(`vsApi.assistantCheckKey('openai','sk-test-replacement')`);
    assert.equal(failed.ok, false);
    assert.match(failed.error, /Прежний ключ остался/);
    assert.deepEqual(await fs.readFile(keyFile), old);
    assert.equal((await page.ev(`vsApi.assistantCheckKey('openai','')`)).ok, true);
    assert.ok(seen[seen.length - 1].endsWith('sk-test-first'));
    await main.ev(`process.mainModule.require('fs').promises.rename=global.snowKeyRename; true`);
    await page.ev(`window.slowKey=vsApi.assistantCheckKey('openai','sk-test-slow-delete'); true`);
    await waitHeld('delete');
    assert.equal((await page.ev(`vsApi.assistantDeleteKey('openai')`)).ok, true);
    held.get('delete')();
    const late = await page.ev('window.slowKey');
    assert.equal(late.ok, false);
    await assert.rejects(fs.access(keyFile), { code: 'ENOENT' });
    assert.equal((await page.ev('vsApi.load()')).info.assistant.keys.openai, false);
    await page.ev(`window.oldKey=vsApi.assistantCheckKey('openai','sk-test-slow-old'); true`);
    await waitHeld('old');
    assert.equal((await page.ev(`vsApi.assistantCheckKey('openai','sk-test-newer')`)).ok, true);
    held.get('old')();
    assert.equal((await page.ev('window.oldKey')).ok, false);
    assert.equal((await page.ev(`vsApi.assistantCheckKey('openai','')`)).ok, true);
    assert.ok(seen[seen.length - 1].endsWith('sk-test-newer'));
    await main.ev(`(() => {const fs=process.mainModule.require('fs').promises;
      global.keyWriteStarted=false;global.keyWriteGate=new Promise(resolve=>{global.releaseKeyWrite=resolve});
      fs.rename=async(from,to)=>{if(to===${JSON.stringify(keyFile)}){global.keyWriteStarted=true;await global.keyWriteGate}return global.snowKeyRename(from,to)};return true;})()`);
    await page.ev(`window.writingKey=vsApi.assistantCheckKey('openai','sk-test-inflight'); true`);
    await main.until('global.keyWriteStarted');
    await page.ev(`window.deletingKey=vsApi.assistantDeleteKey('openai'); true`);
    await main.ev('global.releaseKeyWrite(); true');
    assert.equal((await page.ev('window.writingKey')).ok, true);
    assert.equal((await page.ev('window.deletingKey')).ok, true);
    await assert.rejects(fs.access(keyFile), { code: 'ENOENT' });
    await main.ev(`process.mainModule.require('fs').promises.rename=global.snowKeyRename; true`);
    page.close(); main.close(); await stop();

    const profile2 = path.join(tmp, 'unreadable-profile'), data2 = path.join(tmp, 'data2');
    await fs.mkdir(profile2); await fs.mkdir(data2);
    await fs.writeFile(path.join(profile2, 'settings.json'), JSON.stringify({ dataDir: data2 }));
    await fs.writeFile(path.join(data2, 'profile.json'), JSON.stringify({ name: 'Тест', welcomed: true }));
    const brokenKey = path.join(profile2, 'openai-key.bin');
    await fs.writeFile(brokenKey, 'not a valid encrypted key');
    [inspectPort, debugPort] = await Promise.all([freePort(), freePort()]);
    child = launch(profile2, inspectPort, debugPort);
    const main2 = await connect(inspectPort, (t) => t.type === 'node');
    assert.equal(path.resolve(await main2.ev("process.mainModule.require('electron').app.getPath('userData')")), path.resolve(profile2));
    const page2 = await connect(debugPort, (t) => /index\.html/.test(t.url));
    await page2.until('!!window.vsApi && document.readyState === "complete"');
    await page2.until(`document.querySelector('[data-provider="openai"] .set-status').textContent.includes('не удалось прочитать')`);
    const rejected = await page2.ev(`vsApi.assistantCheckKey('openai','sk-test-new')`);
    assert.equal(rejected.ok, false);
    assert.equal(await fs.readFile(brokenKey, 'utf8'), 'not a valid encrypted key');
    assert.equal(await page2.ev(`document.querySelector('[data-provider="openai"] .set-delete').hidden`), false);
    await page2.ev(`document.querySelector('[data-provider="openai"] .set-delete').click(); true`);
    await page2.until(`document.querySelector('[data-provider="openai"] .set-status').textContent.includes('Ключа нет')`);
    assert.equal((await page2.ev(`vsApi.assistantCheckKey('openai','sk-test-new')`)).ok, true);
    const encryptedBeforeRestart = await fs.readFile(brokenKey);
    assert.equal(await main2.ev(`process.mainModule.require('electron').safeStorage.decryptString(process.mainModule.require('fs').readFileSync(${JSON.stringify(brokenKey)}))==='sk-test-new'`), true);
    await main2.ev(`setTimeout(()=>process.mainModule.require('electron').app.quit(),50); true`);
    page2.close(); main2.close();
    await new Promise((resolve) => child.exitCode !== null ? resolve() : child.once('exit', resolve));
    child = null;
    [inspectPort, debugPort] = await Promise.all([freePort(), freePort()]);
    child = launch(profile2, inspectPort, debugPort);
    const main3 = await connect(inspectPort, (t) => t.type === 'node');
    assert.equal(path.resolve(await main3.ev("process.mainModule.require('electron').app.getPath('userData')")), path.resolve(profile2));
    const page3 = await connect(debugPort, (t) => /index\.html/.test(t.url));
    await page3.until('!!window.vsApi && document.readyState === "complete"');
    const reloaded = await page3.ev('vsApi.load()');
    if (!reloaded.info.assistant.keys.openai) {
      console.error('Reloaded key status:', reloaded.info.assistant.keyWarnings, 'file present:', await fs.stat(brokenKey).then(() => true, () => false));
      console.error('Encryption available:', await main3.ev(`process.mainModule.require('electron').safeStorage.isEncryptionAvailable()`));
      console.error('Encrypted bytes unchanged:', (await fs.readFile(brokenKey)).equals(encryptedBeforeRestart));
      console.error('Decryption check:', await main3.ev(`(()=>{try{return {ok:process.mainModule.require('electron').safeStorage.decryptString(process.mainModule.require('fs').readFileSync(${JSON.stringify(brokenKey)}))==='sk-test-new'}}catch(e){return {ok:false,code:e.code||e.name, message:String(e.message).slice(0,120)}}})()`));
    }
    assert.equal(reloaded.info.assistant.keys.openai, true);
    assert.equal((await page3.ev(`vsApi.assistantCheckKey('openai','')`)).ok, true);
    assert.ok(seen[seen.length - 1].endsWith('sk-test-new'));
    assert.equal((await page3.ev(`vsApi.assistantCheckKey('openai','sk-test-abrupt')`)).ok, true);
    await page3.sleep(3000);
    page3.close(); main3.close(); await stop();
    [inspectPort, debugPort] = await Promise.all([freePort(), freePort()]);
    child = launch(profile2, inspectPort, debugPort);
    const main4 = await connect(inspectPort, (t) => t.type === 'node');
    const page4 = await connect(debugPort, (t) => /index\.html/.test(t.url));
    await page4.until('!!window.vsApi && document.readyState === "complete"');
    assert.equal((await page4.ev('vsApi.load()')).info.assistant.keys.openai, true);
    assert.equal((await page4.ev(`vsApi.assistantCheckKey('openai','')`)).ok, true);
    assert.ok(seen[seen.length - 1].endsWith('sk-test-abrupt'));
    page4.close(); main4.close(); await stop();
    const profile3 = path.join(tmp, 'fresh-profile'), data3 = path.join(tmp, 'data3');
    await fs.mkdir(profile3); await fs.mkdir(data3);
    await fs.writeFile(path.join(profile3, 'settings.json'), JSON.stringify({ dataDir: data3 }));
    await fs.writeFile(path.join(data3, 'profile.json'), JSON.stringify({ name: 'Тест', welcomed: true }));
    [inspectPort, debugPort] = await Promise.all([freePort(), freePort()]);
    child = launch(profile3, inspectPort, debugPort);
    const main5 = await connect(inspectPort, (t) => t.type === 'node');
    const page5 = await connect(debugPort, (t) => /index\.html/.test(t.url));
    await page5.until('!!window.vsApi && document.readyState === "complete"');
    const firstSave = await page5.ev(`vsApi.assistantCheckKey('openai','sk-test-first-crash')`);
    assert.equal(firstSave.ok, true);
    assert.match(firstSave.keyStorageWarning, /внезапном сбое/);
    await page5.ev(`document.querySelector('#set-key-openai').value='sk-test-first-crash'; document.querySelector('[data-provider="openai"] .set-key').requestSubmit(); true`);
    await page5.until(`document.querySelector('[data-provider="openai"] .set-msg').textContent.includes('внезапном сбое')`);
    assert.equal(await page5.ev(`document.querySelector('[data-provider="openai"] .set-security-note').hidden`), false);
    await page5.sleep(3000);
    const encryptedBeforeCrash = await fs.readFile(path.join(profile3, 'openai-key.bin'));
    page5.close(); main5.close(); await stop();
    [inspectPort, debugPort] = await Promise.all([freePort(), freePort()]);
    child = launch(profile3, inspectPort, debugPort);
    const main6 = await connect(inspectPort, (t) => t.type === 'node');
    const page6 = await connect(debugPort, (t) => /index\.html/.test(t.url));
    await page6.until('!!window.vsApi && document.readyState === "complete"');
    const afterCrash = await page6.ev('vsApi.load()');
    assert.equal(afterCrash.info.assistant.keys.openai, false);
    assert.equal(afterCrash.info.assistant.keyWarnings.openai, true);
    assert.deepEqual(await fs.readFile(path.join(profile3, 'openai-key.bin')), encryptedBeforeCrash);
    page6.close(); main6.close();
    console.log('OK: failed saves and key races are safe; normal restart and first-run crash warning verified');
  } finally {
    for (const reply of held.values()) { try { reply(); } catch (e) {} }
    await stop();
    await new Promise((resolve) => server.close(resolve));
    await fs.rm(tmp, { recursive: true, force: true, maxRetries: 20, retryDelay: 250 });
  }
})().catch((e) => { console.error(e); process.exitCode = 1; });
