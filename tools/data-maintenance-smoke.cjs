'use strict';
// Integration check in an isolated profile; no real user data or API keys are used.
const { spawn } = require('node:child_process');
const fs = require('node:fs');
const fsp = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const assert = require('node:assert/strict');
const { connect, freePort } = require('./guide-shots/cdp');
const { extractZip } = require('../archive');

(async () => {
  const root = path.resolve(__dirname, '..');
  const tmp = await fsp.mkdtemp(path.join(os.tmpdir(), 'snowball-maintenance-'));
  const profile = path.join(tmp, 'profile'), data = path.join(tmp, 'data');
  const destination = path.join(tmp, 'new-data'), archive = path.join(tmp, 'copy.snowball');
  await fsp.mkdir(profile); await fsp.mkdir(data); await fsp.mkdir(destination);
  await fsp.writeFile(path.join(profile, 'settings.json'), JSON.stringify({ dataDir: data }));
  await fsp.writeFile(path.join(data, 'profile.json'), JSON.stringify({ name: 'Тест', welcomed: true }));
  await fsp.writeFile(path.join(data, 'prompts.json'), JSON.stringify({ format: 'snowball', version: 1, prompts: [{ id: 'p1', title: 'Тест', type: 'Видео', text: 'Текст' }] }));
  await fsp.writeFile(path.join(data, 'tasks.json'), '{broken');
  await fsp.writeFile(path.join(data, 'tasks.backup.json'), JSON.stringify({ tasks: [] }));
  const [inspectPort, debugPort] = await Promise.all([freePort(), freePort()]);
  const child = spawn(require('electron'), ['.', '--inspect=' + inspectPort, '--remote-debugging-port=' + debugPort, '--user-data-dir=' + profile],
    { cwd: root, stdio: 'ignore', windowsHide: true });
  try {
    const main = await connect(inspectPort, (t) => t.type === 'node');
    assert.equal(path.resolve(await main.ev("process.mainModule.require('electron').app.getPath('userData')")), path.resolve(profile));
    const page = await connect(debugPort, (t) => /index\.html/.test(t.url));
    await page.until('!!window.vsApi && document.readyState === "complete"');
    await page.until(`document.querySelector('#banner-text').textContent.includes('tasks.json')`);
    await page.ev(`document.querySelector('[data-page="prompts"]').click(); true`);
    await page.until(`!!document.querySelector('.edit-btn')`);
    await page.ev(`document.querySelector('.edit-btn').click(); document.querySelector('#f-text').value = 'Мой черновик'; true`);
    const changed = await page.ev(`vsApi.savePrompt({item:{id:'p1',title:'Из другого окна',type:'Видео',text:'Новый текст'}})`);
    assert.equal(changed.ok, true);
    await page.ev(`document.querySelector('#editor').requestSubmit(); true`);
    await page.until(`!document.querySelector('#save-btn').disabled && document.querySelector('#form-msg').textContent.includes('Не сохранилось')`);
    assert.equal(await page.ev(`document.querySelector('#f-text').value`), 'Мой черновик');
    assert.match(await page.ev(`document.querySelector('#toast').textContent`), /изменили в другом окне/);
    const image = await page.ev(`vsApi.chatImageSave('chat1','фото.jpg',new Uint8Array([1,2,3]),'jpg')`);
    assert.equal(image.ok, true);
    await fsp.unlink(path.join(data, 'Файлы чатов', 'chat1', image.image.stored));
    await page.ev(`window.testAssistantEvents=[]; window.testAssistantOff=vsApi.onAssistant(x=>window.testAssistantEvents.push(x)); true`);
    const sent = await page.ev(`vsApi.assistantSend([{role:'user',content:'Что на картинке?',images:[${JSON.stringify(image.image.stored)}]}],{chatId:'chat1'})`);
    assert.equal(sent.ok, true);
    await page.until(`window.testAssistantEvents.some(x=>x.kind==='error' && x.id===${sent.id})`);
    assert.match(await page.ev(`window.testAssistantEvents.find(x=>x.kind==='error').error`), /Не удалось прочитать картинку/);
    await main.ev(`process.mainModule.require('electron').dialog.showSaveDialog = async () => ({canceled:false,filePath:${JSON.stringify(archive)}})`);
    const results = await page.ev(`Promise.all([vsApi.backupExport(),vsApi.taskSave({title:'Задача'})])`);
    assert.equal(results[0].ok, true); assert.equal(results[1].ok, true);
    const unpacked = path.join(tmp, 'unpacked');
    await extractZip(archive, unpacked);
    const prompts = JSON.parse(await fsp.readFile(path.join(unpacked, 'prompts.json'), 'utf8'));
    assert.equal(prompts.prompts[0].title, 'Из другого окна');
    await main.ev(`process.mainModule.require('electron').dialog.showOpenDialog = async () => ({canceled:false,filePaths:[${JSON.stringify(destination)}]})`);
    const moved = await page.ev('vsApi.changeDataDir()');
    assert.equal(moved.ok, true); assert.equal(moved.mode, 'copied');
    assert.equal(JSON.parse(await fsp.readFile(path.join(destination, 'tasks.json'), 'utf8')).tasks[0].title, 'Задача');
    const next = await page.ev(`vsApi.taskSave({title:'После переезда'})`);
    assert.equal(next.ok, true);
    assert.equal(JSON.parse(await fsp.readFile(path.join(destination, 'tasks.json'), 'utf8')).tasks.length, 2);
    await page.ev(`document.querySelector('[data-page="tasks"]').click(); true`);
    await page.until(`!!document.querySelector('.task-add')`);
    await page.ev(`document.querySelector('.task-add').click(); const input=document.querySelector('.task-input'); input.value='Тест конфликта'; input.dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',bubbles:true})); true`);
    await page.until(`Array.from(document.querySelectorAll('.task')).some(x=>x.textContent.includes('Тест конфликта'))`);
    const taskId = await page.ev(`(() => { const task=Array.from(document.querySelectorAll('.task')).find(x=>x.textContent.includes('Тест конфликта')); task.click(); return task.dataset.id; })()`);
    await page.until(`!!document.querySelector('.tp-note')`);
    await page.ev(`document.querySelector('.tp-note').focus(); document.querySelector('.tp-note').value='Мой текст задачи'; true`);
    assert.equal((await page.ev(`vsApi.windowOpen([{kind:'tasks'}])`)).ok, true);
    const otherPage = await connect(debugPort, (t) => /index\.html\?tabs=/.test(t.url));
    await otherPage.until('!!window.vsApi && document.readyState === "complete"');
    const other = await otherPage.ev(`vsApi.taskSave({id:${JSON.stringify(taskId)},note:'Новая заметка из другого окна'})`);
    assert.equal(other.ok, true);
    await page.sleep(200);
    assert.equal(await page.ev(`document.querySelector('.tp-note').value`), 'Мой текст задачи');
    await page.ev(`document.querySelector('.tp-note').dispatchEvent(new Event('change',{bubbles:true})); true`);
    await page.until(`document.querySelector('#toast').textContent.includes('Эту часть задачи изменили')`);
    assert.equal(await page.ev(`document.querySelector('.tp-note').value`), 'Мой текст задачи');
    const afterConflict = await page.ev(`vsApi.load()`);
    assert.equal(afterConflict.tasks.find(t => t.id === taskId).note, 'Новая заметка из другого окна');
    otherPage.close();
    page.close(); main.close();
    console.log('OK: recovery, backup, folder change, prompt and task conflicts, missing image');
  } finally {
    child.kill();
    await new Promise((resolve) => child.exitCode !== null ? resolve() : child.once('exit', resolve));
    await fsp.rm(tmp, { recursive: true, force: true, maxRetries: 20, retryDelay: 250 });
  }
})().catch((e) => { console.error(e); process.exitCode = 1; });
